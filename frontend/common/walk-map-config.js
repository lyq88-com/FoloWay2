// ============ 辅助函数 ============

/**
 * 根据总打卡次数获取当前关卡
 */
export function getCurrentStage(totalCheckins) {
  for (let i = MAP_STAGES.length - 1; i >= 0; i--) {
    if (totalCheckins >= MAP_STAGES[i].threshold) {
      return MAP_STAGES[i]
    }
  }
  return MAP_STAGES[0]
}

/**
 * 获取当前关卡内的进度 (0-1)
 */
export function getStageProgress(totalCheckins) {
  const stage = getCurrentStage(totalCheckins)
  if (stage.nextThreshold === Infinity) {
    // 最终关卡，进度基于额外步数
    const extra = totalCheckins - stage.threshold
    return Math.min(extra / 40, 1) // 40步走完全部节点
  }
  const range = stage.nextThreshold - stage.threshold
  const progress = (totalCheckins - stage.threshold) / range
  return Math.min(progress, 1)
}

/**
 * 获取AI角色在地图上的位置百分比 (0-100)
 */
export function getWalkerPosition(totalCheckins) {
  const stage = getCurrentStage(totalCheckins)
  const progress = getStageProgress(totalCheckins)
  // 5% 到 90% 之间移动，留出边距
  return 5 + progress * 85
}

/**
 * 获取下一个里程碑信息
 */
export function getNextMilestone(totalCheckins) {
  const stage = getCurrentStage(totalCheckins)
  if (stage.nextThreshold === Infinity) {
    return { name: '已通关', remaining: 0, needed: 0, total: totalCheckins }
  }
  const remaining = stage.nextThreshold - totalCheckins
  return {
    name: MAP_STAGES[stage.id + 1]?.name || '终点',
    remaining: remaining,
    needed: remaining,
    total: stage.nextThreshold
  }
}

/**
 * 获取当前地点的对话
 */
export function getLocationDialogue(characterId, stageId) {
  const dialogues = LOCATION_DIALOGUES[characterId]
  if (!dialogues || !dialogues[stageId]) {
    // fallback 到林夕
    return LOCATION_DIALOGUES.linxi[stageId] || ['继续走吧，我陪着你~']
  }
  return dialogues[stageId]
}

/**
 * 获取随机地点对话
 */
export function getRandomLocationDialogue(characterId, stageId) {
  const dialogues = getLocationDialogue(characterId, stageId)
  return dialogues[Math.floor(Math.random() * dialogues.length)]
}

/**
 * 获取懈怠关怀对话
 */
export function getInactivityDialogue(characterId) {
  return INACTIVITY_DIALOGUES[characterId] || INACTIVITY_DIALOGUES.linxi
}

/**
 * 获取通关语录
 */
export function getEndingQuote(characterId) {
  return ENDING_QUOTES[characterId] || ENDING_QUOTES.linxi
}

/**
 * 检查是否解锁新关卡
 */
export function checkStageUnlock(prevCheckins, currentCheckins) {
  const prevStage = getCurrentStage(prevCheckins)
  const currStage = getCurrentStage(currentCheckins)
  if (currStage.id > prevStage.id) {
    return {
      unlocked: true,
      newStage: currStage,
      prevStage: prevStage
    }
  }
  return { unlocked: false }
}

/**
 * 检查是否全部通关
 */
export function isAllCompleted(totalCheckins) {
  return totalCheckins >= MAP_STAGES[MAP_STAGES.length - 1].threshold
}
